import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, test } from 'vitest';

/**
 * P1 - THE `files` DECLARATION ITSELF (R4-1).
 *
 * `scripts/pack-verify.sh` directions 1 and 2 compare the packed members
 * against the `files` declaration: direction 1 flags members the declaration
 * does not cover, direction 2 flags declared entries that ship nothing. A
 * declaration entry that is silently REMOVED is invisible to both - dropping
 * `SECURITY.md` and `THIRD-PARTY-LICENSES` from `files[]` passed both
 * directions with no signal anywhere, while the artifact shipped without its
 * security policy and its legal notice.
 *
 * This test pins the declaration itself, read from `package.json`: the exact
 * expected set, no more and no less. Either direction of drift fails:
 *   - a REMOVED entry fails (the silent-shrink this file exists to catch);
 *   - an ADDED entry fails too (a new shipped file is a deliberate decision
 *     - the expected set here AND the direction-3 set in pack-verify.sh are
 *     updated with it, not silently absorbed).
 *
 * The six docs are the reason the blocked-string scan exists at all, and
 * `THIRD-PARTY-LICENSES` is the package's shipped legal notice. Each doc is
 * also asserted to EXIST in the tree, so the declaration cannot pin a file
 * that is not there.
 */
const PKG = JSON.parse(
  readFileSync(fileURLToPath(new URL('../package.json', import.meta.url)), 'utf8'),
) as { files?: unknown };
const ROOT = fileURLToPath(new URL('..', import.meta.url));

const EXPECTED_FILES = [
  'build',
  'bin',
  'README.md',
  'CHANGELOG.md',
  'LICENSE',
  'NOTICE',
  'THIRD-PARTY-LICENSES',
  'SECURITY.md',
] as const;

describe('pack-verification P1 - the `files` declaration is the right one (R4-1)', () => {
  test('package.json declares exactly the expected `files` set - no silent shrink, no silent growth', () => {
    expect(Array.isArray(PKG.files), 'package.json must declare a `files` array').toBe(true);
    const declared = [...(PKG.files as unknown[])].map(String).sort();
    expect(declared).toEqual([...EXPECTED_FILES].sort());
  });

  test('every declared doc exists in the tree (the declaration cannot pin a file that is not there)', () => {
    for (const doc of ['README.md', 'CHANGELOG.md', 'LICENSE', 'NOTICE', 'THIRD-PARTY-LICENSES', 'SECURITY.md'] as const) {
      expect(existsSync(`${ROOT}${doc}`), `${doc} must exist in the tree`).toBe(true);
    }
    // `bin/` is committed; `build/` is deliberately NOT asserted here - it
    // is generated by `pnpm build` / prepack, so a bare `vitest run` on a
    // fresh checkout has no build/ yet. Its presence in the tarball is
    // proven by pack-verify (build-file floor + direction 2), not here.
    expect(existsSync(`${ROOT}bin`), 'bin/ must exist in the tree').toBe(true);
  });

  test('the declaration has no duplicates (a duplicated entry would hold vacuously in the sorted compare)', () => {
    const declared = [...(PKG.files as unknown[])].map(String);
    expect(new Set(declared).size).toBe(declared.length);
  });
});
